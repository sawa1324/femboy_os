; ================================================================================
; Femboy OS - Entry Point (x86-64)
; ================================================================================
; Минимальный entry point для загрузки ядра. Вызывается после инициализации
; со стороны загрузчика Limine.
; 
; Архитектура:
;   1. Limine загружает ядро в память (ядро начинается с _start)
;   2. Сохраняем все регистра, которые лимин может изменить
;   3. Вызываем kernel_main() из main.c

    bit 64
    model flat

    ; =============================================================================
    ; Данные - сообщение о загрузке (выводится после успешной загрузки)
    ; =============================================================================
    .data
        start_msg:
            db "Femboy OS v0.1.0 - Booted!", 0x0A, 0x0A
            db "Initializing kernel...", 0x0A
            db ""

    ; =============================================================================
    ; Текст - глобальные данные
    ; =============================================================================
    .text
    global _start

_start:
    ; Сохраняем все регистры (stack top может быть изменён Limine)
    push rax
    push rbx
    push rcx
    push rdx
    push rsi
    push rdi
    push rbp
    push r8
    push r9
    push r10
    push r11
    push r12
    push r13
    push r14
    push r15

    ; Запускаем kernel_main() из main.c (в C коде объявлен как extern void kernel_main(void);)
    call kernel_main

; ================================================================================
; kernel_main - точка входа из C кода
; Вызывается из entry.asm после успешной инициализации загрузчика Limine.
; ================================================================================
kernel_main:
    push rbp
    mov rbp, rsp

    ; Вызов инициализации ядра (пуста на данный момент)
    call kernel_main_init

    ; Переход к бесконечному циклу main_loop
    call main_loop

; ================================================================================
; kernel_main_init - инициализация ядра
; На данном этапе эта функция пуста, будет заполнена позже:
;   1. Инициализация памяти (flat memory model уже сделан загрузчиком)
;   2. Настройка таймера interrupts
;   3. Инициализация портов ввода-вывода (если нужно)
; ================================================================================
kernel_main_init:
    push rbp
    mov rbp, rsp
    
    ; TODO: Добавить инициализацию компонентов ядра
    
    pop rbp
    ret

; ================================================================================
; main_loop - бесконечный цикл ядра
; ================================================================================
main_loop:
hlt:
    hlt
    jmp hlt

    ; =============================================================================
    ; Стэк (8KB) - выделён в конце файла для доступа из assembly
    ; =============================================================================
    .stack_top:
        times 8192 db 0