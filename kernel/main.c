// Минимальная точка входа ядра. Вызывается из entry.asm после успешной
// инициализации загрузчика Limine.

#include <stdint.h>
#include <stddef.h>
#include <stdbool.h>

// Прототипы функций
void __attribute__((noreturn)) kernel_panic(const char *msg);
void kernel_main_init(void);

extern void main_loop(void);

// ================================================================================
// Kernel Panic Handler - остановка системы при фатальной ошибке
// ================================================================================
void __attribute__((noreturn)) kernel_panic(const char *msg) {
    // На данном этапе просто зацикливаем ядро с HLT (halt and catch fire)
    for (;;) {
        asm volatile("hlt");
        asm volatile("jmp $0f");
        asm volatile("cli");  // Отключаем прерывания
        asm volatile("hlt");
        asm volatile("sti");  // Включаем прерывания
        asm volatile("jmp $1f");
        asm volatile("cli");
        asm volatile("hlt");
        asm volatile("sti");
        asm volatile("jmp $2f");
        asm volatile("cli");
        asm volatile("hlt");
    }
}

