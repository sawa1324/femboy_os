SHADES = {
    ' ': 0,
    '.': 35,
    ':': 65,
    '-': 90,
    '=': 120,
    '+': 145,
    '*': 170,
    '#': 200,
    '%': 225,
    '@': 255,
}

rows = [line for line in ART.strip("\n").splitlines()]
width = max(map(len, rows))
height = len(rows)

pixels = []
for row in rows:
    row = row.ljust(width)
    pixels.extend(SHADES[c] for c in row)

output = Path("kernel/src/assets/logo.h")
output.parent.mkdir(parents=True, exist_ok=True)

with output.open("w") as f:
    f.write("#ifndef FEMBOY_LOGO_H\n#define FEMBOY_LOGO_H\n\n")
    f.write("#include <stdint.h>\n\n")
    f.write(f"#define LOGO_WIDTH {width}\n")
    f.write(f"#define LOGO_HEIGHT {height}\n\n")
    f.write("static const uint8_t logo_pixels[LOGO_WIDTH * LOGO_HEIGHT] = {\n")
    for i in range(0, len(pixels), 24):
        f.write("    " + ", ".join(map(str, pixels[i:i+24])) + ",\n")
    f.write("};\n\n#endif\n")

print(f"Logo generated: {width}x{height}")
print(f"Saved to: {output}")
